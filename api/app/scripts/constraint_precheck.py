"""Would pending migrations' constraint changes fail on this database? Read-only (#158).

A migration adds a CHECK constraint ``NOT VALID`` and then validates it; the validation
fails (and the whole migration rolls back) if any existing row breaks it. A migration
that drops a constraint by name (to re-create it, e.g. with another ON DELETE rule) fails
if that database names it differently. Run this against a database *before* applying
such migrations to see both first:

    make db-constraint-check                      # this stack's database, pending migrations
    make db-constraint-check DB_CONTAINER=<name>  # another stack's database

or by hand (it prints SQL; the session is read-only):

    python3 api/app/scripts/constraint_precheck.py migrations/079_db_guardrails.sql \\
      | docker exec -i -e PGOPTIONS='-c default_transaction_read_only=on' <container> \\
          psql -X -v ON_ERROR_STOP=1 -U capitalos -d capitalos

It reads, one statement per line, every
``ALTER TABLE <t> ADD CONSTRAINT <name> CHECK (<expr>) NOT VALID;`` and every
``ALTER TABLE <t> DROP CONSTRAINT <name>;`` (without IF EXISTS) in the given files and
prints one read-only query: per CHECK, how many rows break it and which values they hold
(enum-like status and kind values, never amounts or names); per drop, whether the
constraint is there. The query runs in a READ ONLY transaction and ends by raising an
error, so psql exits non-zero, when anything would fail.

Standard library only: the Makefile runs it with the host's Python, the tests import it.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

_NAME = r"[a-z_][a-z0-9_]*"
_CHECK = re.compile(
    rf"^\s*ALTER\s+TABLE\s+(?:ONLY\s+)?(?P<table>{_NAME})\s+"
    rf"ADD\s+CONSTRAINT\s+(?P<name>{_NAME})\s+"
    r"CHECK\s*\((?P<expr>.*)\)\s+NOT\s+VALID\s*;\s*$",
    re.IGNORECASE,
)
_DROP = re.compile(
    rf"^\s*ALTER\s+TABLE\s+(?:ONLY\s+)?(?P<table>{_NAME})\s+DROP\s+CONSTRAINT\s+(?P<name>{_NAME})\s*;\s*$",
    re.IGNORECASE,
)
_IDENT = re.compile(r"\b([a-z_][a-z0-9_]*)\b")
_SQL_WORDS = {"in", "is", "not", "null", "or", "and"}


@dataclass(frozen=True)
class Check:
    table: str
    name: str
    expr: str

    @property
    def column(self) -> str:
        """The column the check is about: the first identifier outside quotes."""
        unquoted = re.sub(r"'[^']*'", "''", self.expr)
        for word in _IDENT.findall(unquoted):
            if word.lower() not in _SQL_WORDS:
                return word
        raise ValueError(f"No column in CHECK expression of {self.name}: {self.expr}")


@dataclass(frozen=True)
class Drop:
    table: str
    name: str


def parse_checks(sql: str) -> list[Check]:
    """The NOT VALID CHECK constraints a migration adds, in file order."""
    return [
        Check(m["table"], m["name"], m["expr"].strip()) for m in map(_CHECK.match, sql.splitlines()) if m
    ]


def parse_drops(sql: str) -> list[Drop]:
    """The constraints a migration drops by name (without IF EXISTS), in file order."""
    return [Drop(m["table"], m["name"]) for m in map(_DROP.match, sql.splitlines()) if m]


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _check_select(check: Check) -> str:
    return (
        f"  SELECT {_literal(check.name)} AS constraint_name, {_literal(check.table)} AS table_name,\n"
        f"         {_literal('check ' + check.column)} AS what, COUNT(*) AS problems,\n"
        f"         COALESCE(string_agg(DISTINCT COALESCE({check.column}::text, 'NULL'), ', '), '') AS detail\n"
        f"  FROM {check.table} WHERE ({check.expr}) IS FALSE"
    )


def _drop_select(drop: Drop) -> str:
    exists = (
        "EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = {name} "
        "AND c.conrelid = to_regclass({table}))"
    ).format(name=_literal(drop.name), table=_literal("public." + drop.table))
    return (
        f"  SELECT {_literal(drop.name)} AS constraint_name, {_literal(drop.table)} AS table_name, 'drop' AS what,\n"
        f"         CASE WHEN {exists} THEN 0 ELSE 1 END AS problems,\n"
        f"         CASE WHEN {exists} THEN '' ELSE 'not found: the migration drops it by this name' END AS detail"
    )


def precheck_sql(checks: list[Check], drops: list[Drop] | None = None) -> str:
    """One read-only query over ``checks`` and ``drops``; errors out (non-zero psql exit) on problems."""
    drops = drops or []
    if not checks and not drops:
        return "\\echo 'No pending constraint changes to check.'\n"
    union = "\n  UNION ALL\n".join([_check_select(c) for c in checks] + [_drop_select(d) for d in drops])
    return (
        "-- Generated by api/app/scripts/constraint_precheck.py (#158). Read-only.\n"
        "BEGIN TRANSACTION READ ONLY;\n"
        "SELECT constraint_name, table_name, what, problems, detail FROM (\n"
        f"{union}\n"
        ") results ORDER BY problems DESC, constraint_name;\n"
        "DO $precheck$\n"
        "DECLARE bad bigint;\n"
        "BEGIN\n"
        "  SELECT COALESCE(SUM(problems), 0) INTO bad FROM (\n"
        f"{union}\n"
        "  ) results;\n"
        "  IF bad > 0 THEN\n"
        "    RAISE EXCEPTION '% problem(s): rows a pending CHECK would reject, or constraints a pending "
        "migration drops that are not there (listed above)', bad;\n"
        "  END IF;\n"
        f"  RAISE NOTICE 'All pass: {len(checks)} pending CHECK constraint(s) reject no existing row; "
        f"{len(drops)} constraint(s) to drop are there.';\n"
        "END $precheck$;\n"
        "ROLLBACK;\n"
    )


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    checks: list[Check] = []
    drops: list[Drop] = []
    for path in args:
        sql = Path(path).read_text(encoding="utf-8")
        checks.extend(parse_checks(sql))
        drops.extend(parse_drops(sql))
    sys.stdout.write(precheck_sql(checks, drops))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
