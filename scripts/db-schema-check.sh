#!/bin/sh
# Migrate an empty Postgres 16 and check the result (#154). Used by `make db-schema-check`
# (CI: .github/workflows/pr-validate.yml, job "postgres") and `make db-schema-update`.
#
#   check   1. start a throwaway Postgres (its own compose project, container, port and volume),
#           2. apply every migration in order with `make db-migrate` (the same runner as the
#              real stack), 3. run it again: it must apply nothing and leave the schema as it was,
#           4. diff the schema against the committed migrations/schema.sql,
#           5. run the Postgres-marked tests (pytest -m postgres) against it.
#   update  1-2, then write migrations/schema.sql.
#
# The instance never uses the real stack's ports (5433 / 5434) or containers, and is removed
# at the end (KEEP=1 leaves it running for a look; `make db-schema-check-drop` removes it).
# Env (set by the Makefile): PGCI_NAME, PGCI_PG_PORT, MAKE.
set -eu
cd "$(dirname "$0")/.."

mode=${1:-check}
name=${PGCI_NAME:?set by the Makefile}
port=${PGCI_PG_PORT:?set by the Makefile}
make_cmd=${MAKE:-make}
schema_file=migrations/schema.sql

case "$port" in
  5432|5433|5434|8000|8011|8021) echo "Refusing: port $port belongs to a main/real/test stack." >&2; exit 2 ;;
esac
case "$name" in
  capitalos|capitalos-oss-*|capitalos-postgres) echo "Refusing: '$name' is not a throwaway name." >&2; exit 2 ;;
esac

container="$name-postgres"
# The isolated override reads ISO_*: only Postgres starts, the other ports are never bound
# (0 would be a random one).
export ISO_NAME="$name" ISO_PG_PORT="$port" ISO_API_PORT=0 ISO_GRAFANA_PORT=0 ISO_LOKI_PORT=0
# Fixed credentials for the throwaway database, whatever a local .env says.
export POSTGRES_USER=capitalos POSTGRES_PASSWORD=capitalos POSTGRES_DB=capitalos
compose() {
  COMPOSE_PROJECT_NAME='' COMPOSE_FILE='' docker compose -p "$name" -f docker-compose.yml -f docker-compose.isolated.yml "$@"
}

if [ "$mode" = drop ]; then
  compose down -v --remove-orphans
  exit 0
fi

work=$(mktemp -d "${TMPDIR:-/tmp}/capitalos-schema.XXXXXX")
cleanup() {
  rc=$?
  if [ "${KEEP:-0}" = 1 ]; then
    echo "KEEP=1: $container is still running on 127.0.0.1:$port (make db-schema-check-drop removes it)."
  else
    compose down -v --remove-orphans > /dev/null 2>&1 || true
  fi
  rm -rf "$work"
  exit $rc
}
trap cleanup EXIT INT TERM

# pg_dump of the schema, made stable: no version banner, no per-run \restrict key (pg_dump
# 16.10+), no owner or grants, and a fixed header.
dump_schema() {
  {
    echo "-- CapitalOS schema after every migrations/NNN_*.sql on an empty Postgres 16 (#154)."
    echo "-- Generated by 'make db-schema-update'; CI fails when the migrations produce anything else."
    echo "-- Do not edit by hand."
    docker exec "$container" pg_dump -U capitalos -d capitalos --schema-only --no-owner --no-privileges \
      | sed -e '/^\\restrict /d' -e '/^\\unrestrict /d' -e '/^-- Dumped from database version/d' \
            -e '/^-- Dumped by pg_dump version/d'
  } > "$1"
}

echo "==> Fresh Postgres: $container (127.0.0.1:$port)"
compose down -v --remove-orphans > /dev/null 2>&1 || true
compose up -d postgres

echo "==> Migrating an empty database (make db-migrate)"
"$make_cmd" --no-print-directory db-migrate DB_CONTAINER="$container"

files=$(ls -1 migrations/[0-9][0-9][0-9]_*.sql | wc -l | tr -d ' ')
applied=$(docker exec "$container" psql -X -At -U capitalos -d capitalos -c "SELECT COUNT(*) FROM schema_migrations;")
if [ "$applied" != "$files" ]; then
  echo "FAIL: $files migration files but $applied recorded in schema_migrations." >&2
  exit 1
fi
dump_schema "$work/first.sql"

if [ "$mode" = update ]; then
  cp "$work/first.sql" "$schema_file"
  echo "Wrote $schema_file ($files migrations). Review 'git diff $schema_file' like any other change."
  exit 0
fi

echo "==> Re-running the migrations: must be a no-op"
"$make_cmd" --no-print-directory db-migrate DB_CONTAINER="$container" > "$work/rerun.log"
cat "$work/rerun.log"
if grep '^==> ' "$work/rerun.log" | grep -v '(already applied)$' > /dev/null; then
  echo "FAIL: the second run applied a migration again." >&2
  exit 1
fi
dump_schema "$work/second.sql"
if ! diff -u "$work/first.sql" "$work/second.sql"; then
  echo "FAIL: re-running the migrations changed the schema." >&2
  exit 1
fi

echo "==> Schema vs $schema_file"
if [ ! -f "$schema_file" ]; then
  echo "FAIL: $schema_file is missing; run 'make db-schema-update' and commit it." >&2
  exit 1
fi
if ! diff -u "$schema_file" "$work/first.sql"; then
  echo "FAIL: the migrations produce a different schema than $schema_file (diff above: - committed, + migrated)." >&2
  echo "      If the change is intended, run 'make db-schema-update' and commit $schema_file with the migration." >&2
  exit 1
fi

echo "==> Postgres tests (pytest -m postgres)"
# The tests copy the migrated database (CREATE DATABASE ... TEMPLATE) for each test and drop
# the copy afterwards; nothing else in the suite touches this instance.
compose run --rm --build --no-deps \
  -e TEST_POSTGRES_URL="postgresql://capitalos:capitalos@postgres:5432/capitalos" \
  api-dev pytest -m postgres -p no:cacheprovider

echo "Postgres schema check passed: $files migrations, idempotent, matches $schema_file, Postgres tests green."
